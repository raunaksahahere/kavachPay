import { desc, eq } from 'drizzle-orm';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { Db } from '@/db/client';
import { evalRuns } from '@/db/schema';
import { pct, type DetectionMetrics } from './metrics';

export type RulesRun = {
  generatedAt: string;
  config: { thresholds: Record<string, number>; weights: Record<string, number> };
  metrics: DetectionMetrics;
};

export type AiRun = {
  generatedAt: string;
  models: { live: string };
  extractor: {
    messages: number;
    /** Screenshot items inside `messages` (multimodal input). */
    images?: { total: number; scamTypeCorrect: number };
    answered: number;
    failed: number;
    fields: Record<string, { correct: number; total: number; accuracy: number | null }>;
    scamDetection: { precision: number | null; recall: number | null; falsePositiveRate: number | null };
    medianLatencyMs: number | null;
  };
  endToEnd: {
    notesAnalysed: number;
    notesFailed: number;
    rulesOnly: DetectionMetrics;
    withAi: DetectionMetrics;
  };
  grounding: { attempted: number; answered: number; grounded: number; passRate: number | null };
};

export async function latestRuns(db: Db): Promise<{ rules: RulesRun | null; ai: AiRun | null }> {
  const latest = async (kind: 'rules' | 'ai') => {
    const [row] = await db
      .select()
      .from(evalRuns)
      .where(eq(evalRuns.kind, kind))
      .orderBy(desc(evalRuns.createdAt))
      .limit(1);
    return row?.results ?? null;
  };
  return { rules: (await latest('rules')) as RulesRun | null, ai: (await latest('ai')) as AiRun | null };
}

function scenarioTable(m: DetectionMetrics): string {
  const lines = [
    '| Scenario | Label | Payments | Flagged (warn or hold) | Held | Recall / false-positive rate |',
    '|---|---|---:|---:|---:|---:|',
  ];
  for (const s of m.scenarios) {
    lines.push(
      `| ${s.scenario} | ${s.isFraud ? 'fraud' : 'legit'} | ${s.total} | ${s.flagged} | ${s.held} | ${pct(s.flagged / s.total)} |`,
    );
  }
  return lines.join('\n');
}

function summaryRows(m: DetectionMetrics): string[] {
  return [
    `| Precision | ${pct(m.precision)} |`,
    `| Recall | ${pct(m.recall)} |`,
    `| False-positive rate | ${pct(m.falsePositiveRate)} |`,
    `| Fraud blocked outright (hold) | ${pct(m.holdRecall)} |`,
    `| Legitimate payments blocked outright (hold) | ${pct(m.holdFalsePositiveRate)} |`,
    `| True positives / false positives / false negatives | ${m.truePositives} / ${m.falsePositives} / ${m.falseNegatives} |`,
  ];
}

export function renderEvalDoc(rules: RulesRun | null, ai: AiRun | null): string {
  const out: string[] = [
    '# Kavach Pay — Evaluation',
    '',
    'Generated by `npm run eval:rules` and `npm run eval:ai`. Every number below is the output of those scripts on the synthetic, labelled dataset produced by `npm run db:seed`. Nothing here is typed by hand.',
    '',
    '**What these numbers are not.** The data is synthetic and the thresholds were tuned on it, so these results describe this dataset. They are not a prediction of performance on real payments.',
    '',
    '"Flagged" means the engine decided warn or hold. "Held" means the payment was blocked for the cooling period.',
    '',
  ];

  out.push('## 1. Rules only (R1–R7)', '');
  if (!rules) {
    out.push('_Not run yet. Run `npm run eval:rules`._', '');
  } else {
    const m = rules.metrics;
    out.push(
      `Run at ${rules.generatedAt}. ${m.transactions} labelled payments: ${m.fraud} fraud, ${m.legit} legitimate.`,
      '',
      '| Metric | Value |',
      '|---|---:|',
      ...summaryRows(m),
      '',
      '### Per scenario',
      '',
      scenarioTable(m),
      '',
      '### How often each rule fired',
      '',
      '| Rule | On fraud | On legitimate |',
      '|---|---:|---:|',
      ...Object.entries(m.ruleFires)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([id, f]) => `| ${id} | ${f.fraud} | ${f.legit} |`),
      '',
      `Thresholds: warn at ${rules.config.thresholds.warn}, hold at ${rules.config.thresholds.hold}. Weights: ${Object.entries(
        rules.config.weights,
      )
        .map(([k, v]) => `${k.split('_')[0]}=${v}`)
        .join(', ')}.`,
      '',
    );
  }

  out.push('## 2. What Gemini adds (R8)', '');
  if (!ai) {
    out.push('_Not run yet. Run `npm run eval:ai` with `GEMINI_API_KEY` set._', '');
  } else {
    const e = ai.endToEnd;
    const delta = (a: number | null, b: number | null) =>
      a === null || b === null ? 'n/a' : `${((b - a) * 100 >= 0 ? '+' : '') + ((b - a) * 100).toFixed(1)} pts`;
    out.push(
      `Run at ${ai.generatedAt} with model \`${ai.models.live}\`.`,
      '',
      '### End to end: the same payments, with and without R8',
      '',
      `Gemini analysed the ${e.notesAnalysed} distinct payment notes in the dataset (${e.notesFailed} failed and were treated as "no signal"). Its signals were converted to R8 points by the fixed table, capped at +25.`,
      '',
      '| Metric | Rules only | Rules + Gemini | Change |',
      '|---|---:|---:|---:|',
      `| Recall | ${pct(e.rulesOnly.recall)} | ${pct(e.withAi.recall)} | ${delta(e.rulesOnly.recall, e.withAi.recall)} |`,
      `| Precision | ${pct(e.rulesOnly.precision)} | ${pct(e.withAi.precision)} | ${delta(e.rulesOnly.precision, e.withAi.precision)} |`,
      `| False-positive rate | ${pct(e.rulesOnly.falsePositiveRate)} | ${pct(e.withAi.falsePositiveRate)} | ${delta(e.rulesOnly.falsePositiveRate, e.withAi.falsePositiveRate)} |`,
      `| Fraud caught (true positives) | ${e.rulesOnly.truePositives} | ${e.withAi.truePositives} | ${e.withAi.truePositives - e.rulesOnly.truePositives >= 0 ? '+' : ''}${e.withAi.truePositives - e.rulesOnly.truePositives} |`,
      `| Legitimate payments flagged (false positives) | ${e.rulesOnly.falsePositives} | ${e.withAi.falsePositives} | ${e.withAi.falsePositives - e.rulesOnly.falsePositives >= 0 ? '+' : ''}${e.withAi.falsePositives - e.rulesOnly.falsePositives} |`,
      '',
      '### Per scenario, with Gemini',
      '',
      scenarioTable(e.withAi),
      '',
      '### Extractor accuracy (G1)',
      '',
      `${ai.extractor.messages} labelled synthetic items in \`eval/messages/\`${ai.extractor.images ? ` (${ai.extractor.messages - ai.extractor.images.total} texts, ${ai.extractor.images.total} screenshots)` : ''}; ${ai.extractor.answered} returned a schema-valid answer, ${ai.extractor.failed} did not (timeout, error or invalid output) and count as wrong.`,
      ai.extractor.images ? `Screenshots: scam type correct on ${ai.extractor.images.scamTypeCorrect} of ${ai.extractor.images.total}.` : '',
      '',
      '| Field | Correct | Accuracy |',
      '|---|---:|---:|',
      ...Object.entries(ai.extractor.fields).map(
        ([field, f]) => `| \`${field}\` | ${f.correct} / ${f.total} | ${pct(f.accuracy)} |`,
      ),
      '',
      `Scam versus legitimate (any scam type versus \`none\`): precision ${pct(ai.extractor.scamDetection.precision)}, recall ${pct(ai.extractor.scamDetection.recall)}, false-positive rate ${pct(ai.extractor.scamDetection.falsePositiveRate)}.`,
      ai.extractor.medianLatencyMs === null
        ? ''
        : `Median latency of answered calls: ${Math.round(ai.extractor.medianLatencyMs)} ms.`,
      '',
      '### Grounding check (G2)',
      '',
      `${ai.grounding.attempted} explanations requested across English, Hindi and Bengali; ${ai.grounding.answered} answered; ${ai.grounding.grounded} passed the check that every number in the text appears in the rule facts. Pass rate: ${pct(ai.grounding.passRate)} of answered. Explanations that fail are replaced by the deterministic template.`,
      '',
    );
  }
  return out.join('\n');
}

export async function writeEvalDoc(db: Db): Promise<string> {
  const { rules, ai } = await latestRuns(db);
  const file = path.resolve(process.cwd(), 'docs', 'eval.md');
  await writeFile(file, renderEvalDoc(rules, ai));
  return 'docs/eval.md';
}
